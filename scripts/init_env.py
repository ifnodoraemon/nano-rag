#!/usr/bin/env python3
"""Generate docker/.env with the secrets the stack needs, and nothing more.

The compose stack only needs two kinds of *external* credential - a generation
model and (optionally) a document parser. Everything else is either fixed
internal wiring, derived from another variable, or a random secret that no human
needs to invent. This script writes all of it in one shot so the operator never
has to run openssl by hand or remember which pairs must match.

    python scripts/init_env.py                  # create docker/.env
    python scripts/init_env.py --check          # report what is missing, change nothing
    python scripts/init_env.py --force          # regenerate (rotates secrets)

Keys are generated with `secrets.token_hex`
(equivalent to `openssl rand -hex 32`).
"""

from __future__ import annotations

import argparse
import json
import secrets
import shutil
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENV_PATH = ROOT / "docker" / ".env"

# Variables that must be supplied by a human. Everything else is generated.
REQUIRED_EXTERNAL = (
    "GENERATION_API_KEY",
    "DOCUMENT_PARSER_API_KEY",
)

# Legacy names accepted on read (older docker/.env files used the COMPOSE_
# prefix). Writing always uses the canonical GENERATION_*/DOCUMENT_PARSER_*.
LEGACY_ALIASES = {
    "GENERATION_API_KEY": "COMPOSE_GENERATION_API_KEY",
    "GENERATION_API_BASE_URL": "COMPOSE_GENERATION_API_BASE_URL",
    "GENERATION_MODEL_ALIAS": "COMPOSE_GENERATION_MODEL_ALIAS",
    "DOCUMENT_PARSER_PROVIDER": "COMPOSE_DOCUMENT_PARSER_PROVIDER",
    "DOCUMENT_PARSER_API_KEY": "COMPOSE_DOCUMENT_PARSER_API_KEY",
    "DOCUMENT_PARSER_API_BASE_URL": "COMPOSE_DOCUMENT_PARSER_API_BASE_URL",
    "DOCUMENT_PARSER_MODEL": "COMPOSE_DOCUMENT_PARSER_MODEL",
    "POSTGRES_PASSWORD": "PG_PASSWORD",
}

# Generated automatically; never typed by hand.
GENERATED_SECRETS = (
    "RAG_API_KEYS",
    "RAG_ADMIN_API_KEYS",
    "POSTGRES_PASSWORD",
)

TEMPLATE = """\
# Generated by scripts/init_env.py - do not commit (docker/.env is git-ignored).
#
# Only TWO entries need your input: GENERATION_API_KEY, and
# DOCUMENT_PARSER_API_KEY (required: parsing is model-only).
# Everything else below is generated or derived.

# ---------- 1. 外部凭据：你只需要填这两个 ----------
# 生成模型：对话、阅读计划、图抽取都走它（Gemini 或 Qwen/DashScope 兼容端点）。
GENERATION_API_KEY={generation_api_key}
GENERATION_API_BASE_URL={generation_base_url}
GENERATION_MODEL_ALIAS={generation_model}

# 文档解析模型：只在摄入 PDF / 图片 / Office 时需要；纯 md/txt 可以留空。
DOCUMENT_PARSER_PROVIDER={parser_provider}
DOCUMENT_PARSER_API_KEY={parser_api_key}
DOCUMENT_PARSER_API_BASE_URL={parser_base_url}
DOCUMENT_PARSER_MODEL={parser_model}

# ---------- 2. 自动生成的密钥（无需修改） ----------
# 业务密钥（浏览器不需要它，nginx 会为业务路由注入；必须是单个 key）。
RAG_API_KEYS={rag_api_key}
# 运维密钥：注入/追踪/评测/回放/health/detail 需要它，必须与业务密钥不同。
RAG_ADMIN_API_KEYS={rag_admin_key}
# 内部 PostgreSQL 密码（服务未对外发布，仅容器网络内使用）。
POSTGRES_PASSWORD={postgres_password}

# ---------- 3. 运行环境 ----------
# local 允许弱默认密钥（开发用）；prod 会拒绝已知弱密钥。
RAG_ENV={rag_env}

# ---------- 4. 可选 ----------
# 前端监听地址：默认只绑本机。改成 0.0.0.0 前请确认你在前面放了鉴权代理。
FRONTEND_BIND=127.0.0.1
FRONTEND_PORT=3001

# cross-encoder 重排（默认关闭）。开启需要同时给 BASE_URL 和 PATH。

# 摄入并发（Celery worker 数）
RAG_WORKER_CONCURRENCY=32
"""


def _parse_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, _, value = stripped.partition("=")
        values[key.strip()] = value.strip()
    return values


def _lookup(values: dict[str, str], name: str) -> str | None:
    """Read a canonical name, falling back to its legacy alias."""
    if _has_real_value(values.get(name)):
        return values[name]
    legacy = LEGACY_ALIASES.get(name)
    if legacy:
        legacy_value = values.get(legacy)
        if _has_real_value(legacy_value):
            return legacy_value
    return values.get(name)


def _has_real_value(value: str | None) -> bool:
    """An empty or placeholder value is not supplied."""
    if not value:
        return False
    token = value.strip()
    if not token:
        return False
    lowered = token.lower()
    return not any(
        marker in lowered for marker in ("<", "your-", "changeme", "xxx")
    )


def _probe_provider(base_url: str, api_key: str, timeout: float = 15.0) -> tuple[bool, str]:
    """Ask the provider whether the key is actually usable.

    A syntactically plausible key (right prefix and length) can still be dead -
    revoked, wrong project, quota exhausted. Testing it here turns a confusing
    runtime failure into one clear line before anything is deployed.
    """
    base = base_url.rstrip("/")
    if not base:
        # No base URL in the file: probe the documented default rather than
        # building a relative "/models" URL that cannot resolve.
        base = "https://generativelanguage.googleapis.com/v1beta/openai"
    # host.docker.internal only resolves INSIDE a container. This check runs on
    # the host, so map it to localhost - otherwise a perfectly good gateway
    # looks unreachable and sends people chasing a nonexistent problem.
    base = base.replace("host.docker.internal", "localhost").replace(
        "//gateway.docker.internal", "//localhost"
    )
    attempts: list[tuple[str, dict[str, str] | None]] = [
        (f"{base}/models", {"Authorization": f"Bearer {api_key}"}),
    ]
    # Native Gemini: the key travels as a query parameter.
    if "generativelanguage.googleapis.com" in base:
        attempts.append((f"{base}/v1beta/models?key={api_key}", None))
        attempts.append((f"{base}/v1/models?key={api_key}", None))

    last_detail = "no endpoint attempted"
    for url, headers in attempts:
        request = urllib.request.Request(url, headers=headers or {})
        reachable, detail, conclusive = _try_probe(request, timeout)
        if conclusive:
            return reachable, detail
        last_detail = detail
    return False, last_detail


def _try_probe(
    request: urllib.request.Request, timeout: float
) -> tuple[bool, str, bool]:
    """Return (ok, detail, conclusive). A 404 means "wrong endpoint shape", not
    "bad key", so the caller can try another path."""
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            raw = response.read().decode("utf-8", "replace")
            try:
                payload = json.loads(raw or "{}")
            except json.JSONDecodeError:
                return True, "reachable (non-JSON response)", True
            count = len(payload.get("data") or payload.get("models") or [])
            return True, f"reachable ({count} model(s) listed)", True
    except urllib.error.HTTPError as exc:
        body = ""
        try:
            body = exc.read().decode("utf-8", "replace")
        except Exception:  # noqa: BLE001 - the body is only diagnostic detail
            body = "<unreadable error body>"
        detail = body.replace("\n", " ").strip()[:200]
        if exc.code == 404:
            return False, f"HTTP 404 (endpoint shape differs): {detail}", False
        if exc.code in (401, 403) or "api key not valid" in body.lower() or "valid api key" in body.lower():
            return False, f"the provider rejected this key (HTTP {exc.code}): {detail}", True
        return False, f"HTTP {exc.code}: {detail}", True
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        return False, f"cannot reach the endpoint: {exc}", True


def check(probe: bool = False) -> int:
    """Report readiness without touching anything."""
    values = _parse_env(ENV_PATH)
    problems: list[str] = []

    if not ENV_PATH.exists():
        problems.append(f"{ENV_PATH} does not exist - run: python scripts/init_env.py")
    for name in GENERATED_SECRETS:
        if not _has_real_value(_lookup(values, name)):
            problems.append(f"{name} is missing (run: python scripts/init_env.py)")
    # The parser key is always required: this build has no local extraction, so
    # every document is parsed by the provider's multimodal model. Switching the
    # parser off makes ingest impossible, which is reported below.
    parser_enabled = (_lookup(values, "DOCUMENT_PARSER_ENABLED") or "true").strip().lower()
    if parser_enabled in {"false", "0", "no", "off"}:
        problems.append(
            "DOCUMENT_PARSER_ENABLED is off, but parsing is model-only in this "
            "build (no local extraction) - every ingest would fail"
        )
    for name in ["GENERATION_API_KEY", "DOCUMENT_PARSER_API_KEY"]:
        if not _has_real_value(_lookup(values, name)):
            problems.append(f"{name} is not filled in - this is the one you must provide")
    model = _lookup(values, "GENERATION_MODEL_ALIAS")
    if not _has_real_value(model):
        problems.append("GENERATION_MODEL_ALIAS is not filled in - set your model id in env")
    parser_model = _lookup(values, "DOCUMENT_PARSER_MODEL")
    if _has_real_value(parser_model) and parser_model != model:
        problems.append("DOCUMENT_PARSER_MODEL must equal GENERATION_MODEL_ALIAS")
    if any(key.startswith("COMPOSE_") for key in values):
        problems.append(
            "this file uses the legacy COMPOSE_* names - run "
            "`python scripts/init_env.py` to migrate in place (values preserved)"
        )
    business = _lookup(values, "RAG_API_KEYS") or ""
    admin = _lookup(values, "RAG_ADMIN_API_KEYS") or ""
    if business and admin and business == admin:
        problems.append(
            "RAG_API_KEYS and RAG_ADMIN_API_KEYS are identical - operator routes "
            "would accept the browser-facing key"
        )
    if "," in business:
        problems.append(
            "RAG_API_KEYS holds several keys but nginx injects exactly one; "
            "keep a single key here (put extra valid keys only if you also set "
            "RAG_PROXY_API_KEY to the first one)"
        )

    if not problems and probe:
        # Both capabilities are always probed: the parser is the only parsing
        # path, so a bad parser key fails every ingest.
        probes = [
            ("generation", "GENERATION_API_KEY", "GENERATION_API_BASE_URL"),
            ("document parser", "DOCUMENT_PARSER_API_KEY", "DOCUMENT_PARSER_API_BASE_URL"),
        ]
        for label, key_name, url_name in probes:
            api_key = _lookup(values, key_name)
            base_url = _lookup(values, url_name) or ""
            if not _has_real_value(api_key):
                continue  # not configured is already reported above
            ok, detail = _probe_provider(str(base_url), str(api_key))
            print(f"  {label:16s} {'OK' if ok else 'FAIL'} - {detail}")
            if not ok:
                problems.append(f"{label} credentials do not work: {detail}")

    if not problems:
        print(f"OK: {ENV_PATH} is ready.")
        if not probe:
            print("    add --probe to verify the provider keys actually work.")
        return 0
    print(f"{ENV_PATH} needs attention:")
    for problem in problems:
        print(f"  - {problem}")
    return 1


def write(force: bool) -> int:
    if ENV_PATH.exists() and not force:
        existing = _parse_env(ENV_PATH)
        legacy_format = any(key.startswith("COMPOSE_") for key in existing)
        missing_secrets = any(
            not _has_real_value(_lookup(existing, name)) for name in GENERATED_SECRETS
        )
        if not legacy_format and not missing_secrets:
            print(f"{ENV_PATH} already exists (use --force to regenerate secrets).")
            return check()
        if legacy_format:
            print("migrating docker/.env to the simplified format (values preserved).")
            backup = ENV_PATH.parent / f"{ENV_PATH.name}.bak"
            shutil.copy2(ENV_PATH, backup)
            print(f"backup: {backup}")
        else:
            print("docker/.env exists but lacks generated secrets; filling them in.")

    existing = _parse_env(ENV_PATH)
    if force and ENV_PATH.exists():
        backup = ENV_PATH.parent / f"{ENV_PATH.name}.bak"
        shutil.copy2(ENV_PATH, backup)
        print(f"backed up existing file to {backup}")

    def keep_or_new(name: str, fallback: str) -> str:
        # Preserve operator-supplied values (provider keys) unless --force,
        # including ones stored under a legacy alias.
        current = _lookup(existing, name)
        if not force and _has_real_value(current):
            return str(current)
        return fallback

    def keep_raw(name: str, fallback: str) -> str:
        current = _lookup(existing, name)
        if not force and current:
            return current
        return fallback

    ENV_PATH.parent.mkdir(parents=True, exist_ok=True)
    ENV_PATH.write_text(
        TEMPLATE.format(
            # section 1: operator-supplied (kept across re-runs)
            generation_api_key=keep_raw("GENERATION_API_KEY", ""),
            generation_base_url=keep_or_new(
                "GENERATION_API_BASE_URL",
                "https://generativelanguage.googleapis.com/v1beta/openai",
            ),
            generation_model=keep_or_new(
                "GENERATION_MODEL_ALIAS", ""
            ),
            parser_provider=keep_or_new("DOCUMENT_PARSER_PROVIDER", "gemini"),
            parser_api_key=keep_raw("DOCUMENT_PARSER_API_KEY", ""),
            parser_base_url=keep_or_new(
                "DOCUMENT_PARSER_API_BASE_URL",
                "https://generativelanguage.googleapis.com",
            ),
            parser_model=keep_or_new("DOCUMENT_PARSER_MODEL",
                keep_or_new("GENERATION_MODEL_ALIAS", "")),
            # section 2: generated
            rag_api_key=keep_or_new("RAG_API_KEYS", secrets.token_hex(32)),
            rag_admin_key=keep_or_new("RAG_ADMIN_API_KEYS", secrets.token_hex(32)),
            postgres_password=keep_or_new(
                "POSTGRES_PASSWORD", secrets.token_hex(24)
            ),
            # section 3: defaults
            rag_env=keep_or_new("RAG_ENV", "local"),
        ),
        encoding="utf-8",
    )
    ENV_PATH.chmod(0o600)
    print(f"wrote {ENV_PATH} (mode 600)")

    # A new database password against an existing data volume is the classic
    # footgun: postgres initialises its password only on first boot, so the
    # stack would fail to authenticate with no obvious cause.
    previous_password = existing.get("POSTGRES_PASSWORD") or existing.get("PG_PASSWORD")
    new_password = _parse_env(ENV_PATH).get("POSTGRES_PASSWORD")
    if previous_password and new_password and previous_password != new_password:
        print()
        print("NOTE: the PostgreSQL password changed.")
        print("  If a database volume already exists it was initialised with the")
        print("  old password and will refuse authentication. Either keep the old")
        print("  value or remove the volume to start fresh:")
        print("    docker compose -f docker/docker-compose.yml down -v")
    print()
    print("Next:")
    print("  1. fill GENERATION_API_KEY and DOCUMENT_PARSER_API_KEY")
    print("  2. python scripts/init_env.py --check")
    print("  3. docker compose -f docker/docker-compose.yml up -d --build")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="report only, change nothing (add --probe to test the provider keys)",
    )
    parser.add_argument(
        "--probe",
        action="store_true",
        help="also call the provider to check the key is valid (implies --check)",
    )
    parser.add_argument("--force", action="store_true", help="regenerate secrets")
    args = parser.parse_args()
    if args.check or args.probe:
        return check(probe=args.probe)
    return write(args.force)


if __name__ == "__main__":
    sys.exit(main())
